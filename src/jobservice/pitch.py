"""Short application text for a vacancy: the answer to StartupJobs' form field
"Jak mohu vaši firmu posunout vpřed?" (How can I move your company forward?), i.e. a short
cover letter. Generated by Claude Code from the candidate profile and the ad, then cached."""

import hashlib
import sqlite3
from dataclasses import dataclass
from datetime import UTC, datetime

from jobservice.scoring import TRACKS, Runner

PROMPT_VERSION = "1"
LANGUAGES = ("cs", "en")
MAX_CHARS = 2000
MAX_DESCRIPTION_CHARS = 8000

SCHEMA = {
    "type": "object",
    "properties": {
        "language": {"type": "string", "enum": list(LANGUAGES)},
        "text": {"type": "string"},
    },
    "required": ["language", "text"],
    "additionalProperties": False,
}

SYSTEM_PROMPT = """\
You write one candidate's answer to the job-application question "Jak mohu vaši firmu posunout
vpřed?" ("How can I move your company forward?"). It works as a short cover letter. You get the
candidate profile (three base CVs for three career tracks plus preferences) and one job ad.

Rules:
- Language: the language the job ad is written in. Czech ad -> Czech ("cs"), otherwise English
  ("en"). Write natural, simple, correct Czech; no stiff formalities.
- If you write in Czech, include one plain sentence saying the candidate works in English and
  their Czech is at A2-B1 level and improving. Never imply better Czech than that.
- Use the CV of the track that fits this ad best (a hint may be given). Pick the 1-2 projects or
  experiences that prove the ad's key requirements, with concrete evidence (numbers, tools)
  exactly as stated in the profile. Never invent facts, numbers, employers or skills.
- Say specifically what the candidate would do for this company in the first months, based on
  the ad text only. Do not invent facts about the company.
- One short line on practicalities: available immediately, full-time, no work permit or
  sponsorship needed.
- 600-1100 characters, 2-4 short paragraphs separated by blank lines, plain text, no markdown,
  no placeholders, no greeting with an unknown name, no signature block. First person.
- Avoid clichés ("passionate", "team player", "I am writing to apply").
"""


@dataclass(slots=True)
class Pitch:
    language: str
    text: str


def parse_pitch(data: dict) -> Pitch:
    try:
        language, text = data["language"], str(data["text"]).strip()
    except (KeyError, TypeError) as e:
        raise ValueError(f"bad pitch payload: {data!r}") from e
    if language not in LANGUAGES:
        raise ValueError(f"unknown language {language!r}")
    if not text or len(text) > MAX_CHARS:
        raise ValueError(f"pitch length {len(text)} out of range")
    return Pitch(language, text)


def pitch_prompt(row, profile: str) -> str:
    track = dict(row).get("best_track")
    hint = f"Best-fitting track by an earlier screening: {track}\n\n" if track in TRACKS else ""
    description = (row["description_text"] or "")[:MAX_DESCRIPTION_CHARS]
    return (
        f"<candidate_profile>\n{profile.strip()}\n</candidate_profile>\n\n{hint}"
        f"<job_ad>\ntitle: {row['title']}\ncompany: {row['company'] or ''}\n"
        f"city: {row['city'] or ''}\n\n{description}\n</job_ad>"
    )


def input_hash(row, profile: str) -> str:
    parts = (PROMPT_VERSION, profile, row["title"] or "", row["description_text"] or "")
    return hashlib.sha256("\x00".join(parts).encode()).hexdigest()[:16]


def generate(row, profile: str, runner: Runner) -> Pitch:
    return parse_pitch(runner(SYSTEM_PROMPT, pitch_prompt(row, profile), SCHEMA))


# --- storage (table `pitches` is created in db.py) ----------------------------------------------


def get_pitch(conn: sqlite3.Connection, vacancy_id: int) -> sqlite3.Row | None:
    return conn.execute("SELECT * FROM pitches WHERE vacancy_id = ?", (vacancy_id,)).fetchone()


def save_pitch(
    conn: sqlite3.Connection, vacancy_id: int, p: Pitch, model: str | None, ihash: str
) -> None:
    conn.execute(
        "INSERT OR REPLACE INTO pitches VALUES (?, ?, ?, ?, ?, ?, ?)",
        (
            vacancy_id,
            p.text,
            p.language,
            model,
            PROMPT_VERSION,
            ihash,
            datetime.now(UTC).isoformat(timespec="seconds"),
        ),
    )
    conn.commit()
